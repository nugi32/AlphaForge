def render_ea(p: EAPlan) -> str:
    s, ex = p.settings, p.exit
    kind = 0 if ex["kind"] == "T" else 1
    create = []
    for i in p.indicators:
        create.append(f"   H_{i.column}={i.create};")
        create.append(f"   if(H_{i.column}==INVALID_HANDLE){{ PrintFormat(\"%s: cannot create the indicator {i.column}, error %d\",RULE_ID,GetLastError()); return INIT_FAILED; }}")
    release = [f"   if(H_{i.column}!=INVALID_HANDLE) IndicatorRelease(H_{i.column});" for i in p.indicators]
    subs: Dict[str, str] = {
        "HEADER": _header(p), "TF": _PERIOD[s["timeframe"]], "RULE_ID": p.rule.rule_id, "DIR": "1" if s["direction"] == "long" else "-1",
        "EXIT_KIND": str(kind), "EXIT_N": str(ex.get("n", 0)), "EXIT_TP": mql_double(ex.get("tp", 0.0)), "EXIT_SL": mql_double(ex.get("sl", 0.0)),
        "EXIT_H": str(ex.get("h", 0)), "CAT_K": mql_double(s["cat_stop_atr"] or 0.0), "SPREAD": mql_double(s["assumed_spread_points"]),
        "MAGIC": str(s["magic"]), "LOTS": mql_double(s["lots"]), "REENTER": "true" if s["reenter_on_exit_bar"] else "false", "GAP": mql_double(s["max_gap_hours"]),
        "EA_NAME": p.ea_name, "HELPERS": "\n".join(ALL_HELPERS[h][1] for h in p.helpers), "INDICATORS": _indicator_block(p), "ATRCOL": s["atr_column"],
        "SIGNAL": _signal_block(p), "CREATE": "\n".join(create), "RELEASE": "\n".join(release), "FEATURE_NAMES": ",".join(p.feature_names),
    }
    out = TEMPLATE
    for k, v in subs.items():
        out = out.replace(f"@@{k}@@", v)
    left = re.findall(r"@@[A-Z_]+@@", out)
    if left:
        raise RuntimeError(f"unfilled template fields: {sorted(set(left))}")
    return _ascii(out)
