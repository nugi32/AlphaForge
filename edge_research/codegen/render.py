"""``EAPlan`` -> MQL5 source (design 16.2 - 16.5, 16.8). The text is laid out from the plan only; there is no regex rewriting of strings anywhere.

Algorithm of the generated EA (the model in ``ea_sim`` follows the same steps and is compared with the engine in the tests):
  OnTick acts only on the FIRST tick of a new bar. Order: (a) exit of the open position (time stop / bar boundary on the closed bar), (b) dump row (optional),
  (c) entry when flat (and, if ``InpReenterOnExitBar`` is false, no exit happened on this bar): the signal is the AND of the atoms on the closed bar (shift 1).
  Bars held = iBarShift(position open time); the ATR of the signal bar is the ATR at shift held + 1, so nothing has to survive an EA restart.
"""

