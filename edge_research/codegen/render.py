def _comment(text: str, width: int = 118) -> List[str]:
    text = re.sub(r"\*/", "* /", text.replace("\r", " ").replace("\n", " "))
    out, cur = [], ""
    for w in text.split(" "):
        if len(cur) + len(w) + 1 > width:
            out.append("// " + cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    out.append("// " + cur)
    return out


def _ascii(s: str) -> str:
    return s.encode("ascii", "replace").decode("ascii")


def _header(p: EAPlan) -> str:
    r = p.rule
    lines = ["//+------------------------------------------------------------------+",
             f"//| {p.ea_name}.mq5  generated by edge_research.codegen v{CODEGEN_VERSION}",
             "//+------------------------------------------------------------------+",
             "// NOT FOR REAL MONEY until the review checklist below is complete and the parity tests (design 16.6) pass.",
             f"// rule id    : {r.rule_id}", f"// direction  : {r.direction}", f"// exit       : {r.exit}" + (f"  + catastrophic stop {r.cat_stop_atr} x ATR(signal bar)" if r.cat_stop_atr else ""),
             "// atoms (AND): " + "; ".join(f"{a['feature']} {a['op']} {mql_double(a['threshold'])}" for a in r.atoms)]
    if p.provenance:
        lines += _comment("provenance: " + json.dumps(p.provenance, sort_keys=True, default=str))
    if r.meta:
        lines += _comment("expected statistics / meta of the rule: " + json.dumps(r.meta, sort_keys=True, default=str))
    if p.warnings:
        lines.append("// WARNINGS")
        for w in p.warnings:
            lines += _comment("- " + w)
    lines.append("// INDICATOR HANDLES (compare each line with dataExporter.mq5: period, method, applied price, buffer)")
    for i in p.indicators:
        lines.append(f"//   {i.column:<24} {i.create}  buffer {i.buffer}  [{'verified' if i.verified else 'ASSUMED'}: {i.source}]")
    lines += ["// REVIEW CHECKLIST (tick each before live use): indicator handles and buffers | bar shift (all values at shift 1) | direction | one position per magic |",
              "//   exit logic | costs (spread / commission / swap) | custom-indicator dependencies | compile in MetaEditor without warnings | independent tester run |",
              "//   account-level risk management (daily loss limit etc.) is NOT part of this EA.",
              "//+------------------------------------------------------------------+"]
    return "\n".join(lines)


def _indicator_block(p: EAPlan) -> str:
    out = []
    for i in p.indicators:
        out.append(f"int H_{i.column} = INVALID_HANDLE;")
        out.append(f"double IND_{i.column}(const int s)")
        out.append("{")
        out.append(f"   if(H_{i.column}==INVALID_HANDLE) return QNaN();")
        out.append("   double b[1];")
        out.append(f"   if(CopyBuffer(H_{i.column},{i.buffer},s,1,b)!=1) return QNaN();")
        out.append("   if(b[0]==EMPTY_VALUE) return QNaN();")
        out.append("   return b[0];")
        out.append("}")
    return "\n".join(out)


def _signal_block(p: EAPlan) -> str:
    lines = ["// feature values of the rule at the closed bar (shift 1); f[] order: " + ", ".join(f"{i}={r.name}" for i, r in enumerate(p.features)),
             f"const int NF = {len(p.features)};", "bool EvalSignal(double &f[])", "{"]
    for i, r in enumerate(p.features):
        lines.append(f"   f[{i}] = {r.expr};   // {r.name}")
    lines.append("   return (" + "\n        && ".join(p.atom_exprs) + ");")
    lines.append("}")
    return "\n".join(lines)


